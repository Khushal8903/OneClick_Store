package com.oneclick.model;

public class Category {
	
	private int categoryId;
	private String name;
	
	public int getCategoryId() {
		return categoryId;
	}
	public void setCategoryId(int id) {
		this.categoryId = id;
	}
	public String getName() {
		return name;
	}
	public void setName(String name) {
		this.name = name;
	}
}
