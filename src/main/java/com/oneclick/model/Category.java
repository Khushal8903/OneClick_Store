package com.oneclick.model;

public class Category {
	
	private int category_id;
	private String name;
	
	public int getCategoryId() {
		return category_id;
	}
	public void setCategoryId(int id) {
		this.category_id = id;
	}
	public String getName() {
		return name;
	}
	public void setName(String name) {
		this.name = name;
	}
}
